// ---------------------------------------------------------------------------
// CIDR parsing and bitwise prefix-match.
// ---------------------------------------------------------------------------

interface ParsedCidr {
  network: number; // IPv4 as 32-bit unsigned int (high bits first)
  mask: number; // bitmask
}

function ipToUint32(ip: string): number | null {
  const parts = ip.split(".");
  if (parts.length !== 4) return null;
  let n = 0;
  for (let i = 0; i < 4; i++) {
    const oct = Number(parts[i]);
    if (!Number.isInteger(oct) || oct < 0 || oct > 255) return null;
    n = ((n << 8) | oct) >>> 0;
  }
  return n >>> 0;
}

function parseCidr(cidr: string): ParsedCidr | null {
  const slash = cidr.indexOf("/");
  if (slash === -1) return null;
  const ipStr = cidr.slice(0, slash);
  const prefixStr = cidr.slice(slash + 1);
  const prefix = Number(prefixStr);
  if (!Number.isInteger(prefix) || prefix < 0 || prefix > 32) return null;
  const ip = ipToUint32(ipStr);
  if (ip === null) return null;
  const mask = prefix === 0 ? 0 : (0xFFFFFFFF << (32 - prefix)) >>> 0;
  return { network: (ip & mask) >>> 0, mask };
}

function precompile(set: ReadonlySet<string>): ParsedCidr[] {
  const out: ParsedCidr[] = [];
  for (const cidr of set) {
    const parsed = parseCidr(cidr);
    if (parsed !== null) out.push(parsed);
  }
  return out;
}

const VPN_CIDRS = precompile(KNOWN_VPN_RANGES);
const TOR_CIDRS = precompile(TOR_EXIT_NODES);
const RESIDENTIAL_CIDRS = precompile(RESIDENTIAL_PROXY_RANGES);
const CLOUD_CIDRS = precompile(CLOUD_SERVERLESS_RANGES);
const BULLETPROOF_CIDRS = precompile(BULLETPROOF_HOSTING_RANGES);

function ipMatches(ipNum: number, cidrs: ParsedCidr[]): boolean {
  for (const { network, mask } of cidrs) {
    if (((ipNum & mask) >>> 0) === network) return true;
  }
  return false;
}

export type IpClassification =
  | "vpn"
  | "tor"
  | "residential_proxy"
  | "cloud_serverless"
  | "bulletproof"
  | "clean";

/**
 * Classify an IPv4 address against the five threat-intel categories.
 * Order of precedence (most-malicious-wins): tor → bulletproof → vpn →
 * residential_proxy → cloud_serverless → clean. Invalid IPs return "clean"
 * to avoid false positives on degenerate input.
 */
export function classifyIp(ip: string): IpClassification {
  const ipNum = ipToUint32(ip);
  if (ipNum === null) return "clean";
  if (ipMatches(ipNum, TOR_CIDRS)) return "tor";
  if (ipMatches(ipNum, BULLETPROOF_CIDRS)) return "bulletproof";
  if (ipMatches(ipNum, VPN_CIDRS)) return "vpn";
  if (ipMatches(ipNum, RESIDENTIAL_CIDRS)) return "residential_proxy";
  if (ipMatches(ipNum, CLOUD_CIDRS)) return "cloud_serverless";
  return "clean";
}

